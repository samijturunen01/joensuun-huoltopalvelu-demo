/**
 * Optimises the company's authentic photographs (downloaded from the
 * "Ota yhteyttä" rating-plate guide on joensuunhuoltopalvelu.fi) into
 * responsive WebP files, prepares the association badges and renders the
 * Open Graph preview image. Run with `npm run assets`; outputs are committed.
 *
 * Output: public/images/plates/<id>-<w>.webp, public/images/badges/*.webp,
 *         public/images/og-joensuun-huoltopalvelu.jpg, src/data/imageManifest.ts
 */
import sharp from 'sharp'
import fs from 'node:fs/promises'

const PLATES = 'source-assets/plates'
const ORIG = 'source-assets/original'
const WIDTHS = [480, 960, 1600]

/** id → source file. Grouping follows the original guide. */
const plates = {
  'miele-pesukone': 'miele-ppk-kilpi-scaled.jpg',
  'miele-kuivausrumpu': 'miele-kkr-scaled.jpg',
  'miele-uuni': 'miele-uuni-scaled.jpg',
  'miele-astianpesukone': 'miele-apk-scaled.jpg',
  'miele-imuri': 'miele-imuri-scaled.jpg',
  'electrolux-jaakaappi': 'elux-jkpk-tyyppikilpi.jpg',
  'electrolux-pesukone': 'pyykinpesukone-elux.jpg',
  'electrolux-uuni': 'liesi_uuni-elux-scaled.jpg',
  'electrolux-astianpesukone': 'apk-electrolux-scaled.jpg',
  'electrolux-mikro': 'elux-mikro-scaled.jpg',
  'gorenje-jaakaappi': 'upo-jk-kilpi-scaled.jpg',
  'gorenje-pesukone': 'gorenje-ppk-edesta-scaled.jpg',
  'gorenje-pesukone-paalta': 'upo-paaltataytettava-vanha-scaled.jpg',
  'gorenje-uuni': 'upo-liesi-scaled.jpg',
  'gorenje-astianpesukone': 'asko-apk-scaled.jpg',
  'gorenje-keittotaso': 'induktiotaso-upo-scaled.jpg',
  'gorenje-mikro': 'mikro-gorenje-scaled.jpg',
  'bsh-jaakaappi': 'siemens-jk-scaled.jpg',
  'bsh-pesukone': 'bosch-ppk-scaled.jpg',
  'bsh-uuni': 'bosch-uuni-scaled.jpg',
  'bsh-astianpesukone': 'bsh-apk1-scaled.jpg',
  'bsh-mikro': 'bosch-mikro-scaled.jpg',
}

await fs.mkdir('public/images/plates', { recursive: true })
await fs.mkdir('public/images/badges', { recursive: true })

const manifest = {}
for (const [id, file] of Object.entries(plates)) {
  const src = `${PLATES}/${file}`
  const meta = await sharp(src).rotate().metadata()
  manifest[id] = { w: meta.width, h: meta.height }
  for (const w of WIDTHS) {
    await sharp(src)
      .rotate()
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: w > 1000 ? 74 : 78, effort: 5 })
      .toFile(`public/images/plates/${id}-${w}.webp`)
  }
}

// Association badges shown on the original homepage
await sharp(`${ORIG}/SKHL.png`).resize(320).webp({ quality: 88 }).toFile('public/images/badges/skhl-320.webp')
await sharp(`${ORIG}/Luotettava-kumppani_2.png`).resize(720).webp({ quality: 88 }).toFile('public/images/badges/luotettava-kumppani-720.webp')

await fs.writeFile(
  'src/data/imageManifest.ts',
  `// Generated by scripts/prepare-images.mjs – intrinsic sizes of the optimised photos.\nexport const PLATE_WIDTHS = ${JSON.stringify(WIDTHS)} as const\nexport const plateImages = ${JSON.stringify(manifest, null, 2)} as const\nexport type PlateImageId = keyof typeof plateImages\n`,
)

// ---- Open Graph image 1200×630: brand badge + authentic rating-plate photo in a drum window ----
const logo = await fs.readFile('public/brand/logo.svg')
const logoPng = await sharp(logo).resize(560).png().toBuffer()
const D = 420
const photo = await sharp(`${PLATES}/miele-ppk-kilpi-scaled.jpg`)
  .resize(D, D, { fit: 'cover', position: 'centre' })
  .composite([{ input: Buffer.from(`<svg width="${D}" height="${D}"><circle cx="${D / 2}" cy="${D / 2}" r="${D / 2}" fill="#fff"/></svg>`), blend: 'dest-in' }])
  .png()
  .toBuffer()
const ring = Buffer.from(
  `<svg width="1200" height="630" xmlns="http://www.w3.org/2000/svg"><circle cx="930" cy="315" r="${D / 2 + 14}" fill="none" stroke="#f1f2ec" stroke-width="18"/><circle cx="930" cy="315" r="${D / 2 + 46}" fill="none" stroke="#5AC071" stroke-width="3" stroke-dasharray="2 10" opacity=".7"/><text x="60" y="440" font-family="Arial, Helvetica, sans-serif" font-size="26" font-weight="700" fill="#f1f2ec" letter-spacing="1.5">KODINKONEHUOLTO JA VARAOSAT</text><text x="60" y="478" font-family="Arial, Helvetica, sans-serif" font-size="26" font-weight="400" fill="#9fd9ae" letter-spacing="1.5">JOENSUU · VUODESTA 1976</text></svg>`,
)
await sharp({ create: { width: 1200, height: 630, channels: 3, background: '#06140c' } })
  .composite([
    { input: logoPng, left: 60, top: 236 },
    { input: photo, left: 930 - D / 2, top: 315 - D / 2 },
    { input: ring, left: 0, top: 0 },
  ])
  .jpeg({ quality: 86, mozjpeg: true })
  .toFile('public/images/og-joensuun-huoltopalvelu.jpg')

console.log('images prepared:', Object.keys(plates).length, 'plates')
